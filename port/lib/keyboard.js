// 키보드 포트 표본기 0x0AEB8 을 옮긴 것이다.
//
// 이 게임은 인터럽트를 안 쓰고 키보드 컨트롤러 포트 0x60 을 직접 폴링한다. 부르는 곳이
// 넷이고 전부 프레임마다 도는 함수다 — 게임 루프 0x0AC29, 오토파일럿 0x0B33F,
// 탱크 이동 0x0E128, 물체 갱신 0x0F3CA. 뒤의 셋은 프레임마다 한 번이 아니라
// **탱크마다·객체마다** 부르므로, 한 프레임에 이 함수가 몇 번 도는지가 게임 상태에 따라
// 달라진다.
//
// 원본 (22개 명령):
//   al = in(0x60)
//   if (al != [0x4D91 + 0x4D90]) {      직전 항목과 같으면 아무것도 안 한다
//       al = in(0x60)                   포트를 한 번 더 읽는다
//       [0x4D92 + 0x4D90] = al
//       0x4D90++
//   }
//
// ⚠ 정답표를 만들 수 없다. 입력이 계산이 아니라 하드웨어 포트라 골든이 그 값을 기록하지
//   않는다. 게다가 BIOS INT 9 핸들러가 같은 포트를 함께 읽어서 결정론적이지도 않다
//   (CLAUDE.md). 그래서 스캔코드를 **인자로 받는다** — 이 함수는 값을 만드는 곳이 아니라
//   밖에서 들어온 값을 링에 넣는 곳이다. 판정은 나중에 프레임 루프를 락스텝으로 돌릴 때
//   링(`0x4D92`)과 색인(`0x4D90`)을 골든과 견주는 것으로 한다. 그 둘은 프레임 골든의
//   여덟 번째 감시 블록(`0x4D62` 부터 64바이트) 안에 있다.
// @원본 0x0AEB8

                          
                                              
                     
     
                                                          
                                                          
                                            
     
                 
 

/**
 * 원본 0x0AEB8 한 번.
 *
 * @param s        링 상태
 * @param readPort 포트 0x60 을 읽는다. 원본이 두 번 읽으므로 이것도 두 번 부른다 —
 *                 그 사이에 값이 바뀔 수 있는 것이 원본의 성질이다.
 */
export function sampleKeyboard(s         , readPort              )       {
  const first = readPort() & 0xff;                 // 0x0AEBE
  // 0x0AEC0 의 `mov al,[0x4D90]` 다음이 `cbw` 라 색인이 0x80 이상이면 **음수**가 된다.
  // 그러면 원본은 링 앞쪽을 넘어 다른 자리를 읽고 쓴다. 그대로 둔다.
  const idx = (s.writeIndex << 24) >> 24;          // cbw
  if (first === s.at[idx]) return;                 // 0x0AEC7 — 직전 항목과 같으면 끝
  const second = readPort() & 0xff;                // 0x0AED0 — 다시 읽는다
  s.at[idx + 1] = second;                          // 0x0AED9 — 0x4D92 + 색인
  s.writeIndex = (s.writeIndex + 1) & 0xff;        // 0x0AEDD — 바이트 증가
}
